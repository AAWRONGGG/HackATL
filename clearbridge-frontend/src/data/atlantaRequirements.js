const isEntity = (p) => ['llc', 'corporation'].includes(p.structure);
const workerCount = (p) =>
  Number(p.regularWorkers || 0) + (isEntity(p) ? Number(p.officersOrMembers || 0) : 0);
const hasWorkers = (p) => Number(p.regularWorkers || 0) > 0;
const foodService = (p) => p.industry === 'restaurant' && p.foodActivity !== 'packaged';

